/**
 * Stamps content hashes onto every local JS/CSS asset so a deploy can never
 * serve a mixed module graph.
 *
 * Why this exists: the site is hosted on GitHub Pages, which cannot set
 * response headers and sends `Cache-Control: max-age=600` for every file. The
 * old scheme hand-bumped `?v=dev_x.y.z` on the entry script and the CSS only —
 * deep ES-module imports (`./shellResize.js` from `./sidebarDetach.js`) had no
 * version at all, so for up to ten minutes after a deploy a browser could pair
 * a NEW module with a STALE cached one. When the new module imports a name the
 * stale file does not export yet, the whole module graph fails to link, app.js
 * never evaluates, and #app-boot stays on screen forever.
 *
 * Fix: every module URL carries a hash of its own content.
 *   - <script type="module" src> / <link rel="stylesheet"> get `?v=<hash>`.
 *   - An inline <script type="importmap"> maps every `./js/**.js` specifier to
 *     `./js/**.js?v=<hash>`; import maps resolve URL-like keys against the
 *     document base URL, so `./x.js` from js/ and `../board/x.js` from js/board/
 *     both hit the same entry.
 * A changed file always gets a new URL; an unchanged file keeps its URL and
 * stays cached. No header configuration required.
 *
 * Run:  node scripts/build-asset-versions.mjs
 * Check: node scripts/build-asset-versions.mjs --check   (exit 1 when stale)
 */
import fs from 'fs';
import path from 'path';
import { createHash } from 'crypto';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');

const HTML_FILES = ['index.html', 'popout.html'];
const JS_DIR = 'js';
const CSS_DIR = 'css';
const SKIP_DIRS = new Set(['node_modules']);

const BLOCK_START = '<!-- asset-versions:start -->';
const BLOCK_END = '<!-- asset-versions:end -->';
const BLOCK_RE = /[ \t]*<!-- asset-versions:start -->[\s\S]*?<!-- asset-versions:end -->/;
const IMPORTMAP_RE = /<script type="importmap" data-asset-versions>[\s\S]*?<\/script>/;

const checkMode = process.argv.includes('--check');

function walk(dir, out = []) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        if (SKIP_DIRS.has(entry.name) || entry.name.startsWith('.')) continue;
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full, out);
        else if (entry.name.endsWith('.js')) out.push(full);
    }
    return out;
}

function relativeToRoot(filePath) {
    return path.relative(ROOT, filePath).split(path.sep).join('/');
}

function hashFile(filePath) {
    return createHash('sha256').update(fs.readFileSync(filePath)).digest('hex').slice(0, 8);
}

/** hash lookup keyed by root-relative posix path ("js/shellResize.js"). */
function collectHashes() {
    const hashes = new Map();
    const jsFiles = walk(path.join(ROOT, JS_DIR)).sort();
    const cssFiles = fs.readdirSync(path.join(ROOT, CSS_DIR))
        .filter((name) => name.endsWith('.css'))
        .map((name) => path.join(ROOT, CSS_DIR, name))
        .sort();

    for (const file of [...jsFiles, ...cssFiles]) {
        hashes.set(relativeToRoot(file), hashFile(file));
    }
    return hashes;
}


function buildImportMap(hashes) {
    const imports = {};
    [...hashes.keys()]
        .filter((key) => key.startsWith(`${JS_DIR}/`))
        .sort()
        .forEach((key) => {
            imports[`./${key}`] = `./${key}?v=${hashes.get(key)}`;
        });

    const json = JSON.stringify({ imports }, null, 4)
        .split('\n')
        .map((line) => `    ${line}`)
        .join('\n');

    return [
        `    ${BLOCK_START}`,
        '    <!-- Generated by node scripts/build-asset-versions.mjs — do not edit by hand.',
        '         GitHub Pages cannot set cache headers, so every module URL carries a hash of',
        '         its own content: a changed file gets a new URL and can never be mixed with a',
        '         stale cached copy of the module graph. -->',
        `    <script type="importmap" data-asset-versions>\n${json}\n    </script>`,
        `    ${BLOCK_END}`
    ].join('\n');
}

/** Rewrite local ./js/*.js and ./css/*.css references to their hashed URLs. */
function stampAttributes(html, hashes, warnings) {
    const attrRe = /(\s(?:href|src)=")(\.\/(?:js|css)\/[^"?]+\.(?:js|css))(?:\?[^"]*)?(")/g;
    return html.replace(attrRe, (match, prefix, url, suffix) => {
        const key = url.slice(2);
        const hash = hashes.get(key);
        if (!hash) {
            warnings.push(`referenced but missing on disk: ${url}`);
            return match;
        }
        return `${prefix}${url}?v=${hash}${suffix}`;
    });
}

function stampHtml(html, hashes, warnings) {
    const block = buildImportMap(hashes);
    let next = html;
    if (BLOCK_RE.test(next)) {
        next = next.replace(BLOCK_RE, block);
    } else if (IMPORTMAP_RE.test(next)) {
        next = next.replace(IMPORTMAP_RE, block);
    } else if (next.includes('</head>')) {
        next = next.replace('</head>', `${block}\n</head>`);
    } else {
        warnings.push('no </head> to insert the import map into');
    }
    return stampAttributes(next, hashes, warnings);
}

function main() {
    const hashes = collectHashes();
    const warnings = [];
    const stale = [];

    for (const name of HTML_FILES) {
        const filePath = path.join(ROOT, name);
        if (!fs.existsSync(filePath)) {
            warnings.push(`${name} not found`);
            continue;
        }
        const before = fs.readFileSync(filePath, 'utf8');
        const after = stampHtml(before, hashes, warnings);
        if (before !== after) {
            stale.push(name);
            if (!checkMode) fs.writeFileSync(filePath, after);
        }
    }

    warnings.forEach((warning) => console.warn(`[assets] ${warning}`));

    const moduleCount = [...hashes.keys()].filter((key) => key.startsWith(`${JS_DIR}/`)).length;
    const summary = `${moduleCount} modules, ${hashes.size - moduleCount} stylesheets`;

    if (checkMode) {
        if (stale.length) {
            console.error(`[assets] stale asset versions in: ${stale.join(', ')}`);
            console.error('[assets] run: node scripts/build-asset-versions.mjs');
            process.exit(1);
        }
        console.log(`[assets] up to date (${summary})`);
        return;
    }

    if (!stale.length) {
        console.log(`[assets] already up to date (${summary})`);
        return;
    }
    console.log(`[assets] stamped ${stale.join(', ')} (${summary})`);
}

main();
